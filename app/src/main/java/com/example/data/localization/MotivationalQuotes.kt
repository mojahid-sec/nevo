    fun getQuoteForGoal(goalId: String, completedDays: Int, language: AppLanguage): Pair<String, String> {
        val index = (Math.abs(goalId.hashCode()) + completedDays) % quotes.size
        val quote = quotes[index]
        return if (language == AppLanguage.BANGLA) {
            Pair(quote.banglaText, quote.banglaAuthor)
        } else {
            Pair(quote.englishText, quote.englishAuthor)
        }
    }
